/* Третий заход на баг «падает/висит бесконечно» в прятках.

   v1: pl.y > 5000 ловит только сквозное падение за карту, а держа прыжок
   над неполным уступом без бокового движения игрок никуда не падает
   вовсе — приземление тут же снимается held-буфером новым прыжком.

   v2 (сторож по размаху окна: мало места занято + почти всё время в
   воздухе) ловил и настоящий баг, и ЧЕСТНОГО игрока: аккуратный
   платформинг короткими тапами прыжка в тесной шахте — частые прыжки,
   скромное продвижение — даёт для этих же двух признаков картину, не
   отличимую от застревания. Итог — игрока откидывало на спавн посреди
   обычной игры, раз за разом, что для человека выглядит как «вообще не
   могу двигаться». Подтверждено живьём: 10 секунд честных тапов прыжка
   с чередованием влево/вправо в тесной шахте — игрок откинут ровно на
   спавн, ни на пиксель дальше.

   v3 (эта версия): решающий признак — кнопка прыжка была зажата почти
   всё окно целиком (stuckHeld/stuckFrames > 0.85). Только удержание даёт
   мгновенный автоповтор без единого кадра паузы, в который игрок мог бы
   подвинуться. Обычный тап всегда оставляет кадр с отпущенной кнопкой
   между прыжками. Подтверждено: та же тесная шахта с тапами — игрок
   теперь делает реальный прогресс, не откидывается; тот же held-jump
   трюк из v1 — всё ещё спасает через ~5с, как и раньше. */
'use strict';
const fs = require('fs');
let fails = 0;
const ok = (n, c) => { if (!c) fails++; console.log('  ', c ? '✓' : '✗', n); };

['game.html', 'editor.html'].forEach(f => {
  const src = fs.readFileSync(__dirname + '/' + f, 'utf8');
  console.log(f + ':');
  ok('константа окна сторожа объявлена', /STUCK_WINDOW = 150/.test(src));
  ok('состояние сторожа объявлено (включая stuckHeld)',
      /var stuckFrames = 0, stuckAir = 0, stuckHeld = 0, stuckMinX = 0, stuckMaxX = 0, stuckMinY = 0, stuckMaxY = 0;/.test(src));
  ok('respawn\\(\\) обнуляет окно сторожа (включая stuckHeld)',
      /function respawn\(\)\{[\s\S]{0,300}stuckFrames = 0; stuckAir = 0; stuckHeld = 0; stuckMinX = stuckMaxX = pl\.x; stuckMinY = stuckMaxY = pl\.y;/.test(src));
  ok('доля удержания прыжка считается каждый кадр', /if\(keys\.u\) stuckHeld\+\+;/.test(src));
  ok('сторож живёт только в прятках, вне их — сбрасывается (включая stuckHeld)',
      /if\(mode === "hideAndSeek"\)\{\s*if\(pl\.x < stuckMinX\)/.test(src) &&
      /\} else \{\s*stuckFrames = 0; stuckAir = 0; stuckHeld = 0;\s*\}\s*\}\s*function drive/.test(src));
  ok('решающее условие — доля удержания прыжка (> 0.85), а не только размах окна',
      /stuckHeld \/ stuckFrames > 0\.85 && stuckAir \/ stuckFrames > 0\.6 &&\s*\n\s*\(stuckMaxX - stuckMinX\) < 200 && \(stuckMaxY - stuckMinY\) < 200/.test(src));
  ok('застрявшего телепортирует на спавн через respawn\\(\\)',
      /\(stuckMaxY - stuckMinY\) < 200\)\{\s*respawn\(\);/.test(src));
});

console.log(fails ? '\nПРОВАЛЕНО проверок: ' + fails : '\nвсе проверки пройдены ✓');
process.exit(fails ? 1 : 0);
